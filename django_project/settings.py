# Proxmox
# All values come from .env (see .env.example for what each one means).

# Base URL of the Proxmox web UI, as the *student's browser* reaches it.
# Must be a hostname (not an IP) that shares a parent domain with this site,
# otherwise the PVEAuthCookie we set can't be sent to Proxmox. See README.md.
PROXMOX_URL = env.str("PROXMOX_URL")

# Domain the PVEAuthCookie is set on, e.g. ".example.com" makes the browser send
# it to both labs.example.com (this site) and pve.example.com (Proxmox).
PROXMOX_COOKIE_DOMAIN = env.str("PROXMOX_COOKIE_DOMAIN")

# Only send the cookie over HTTPS. Leave True: this site must run on HTTPS anyway
# (even in development; `runserver` in this project serves HTTPS, see README step 5) or browsers won't send the cookie to
# Proxmox inside the iframe.
PROXMOX_COOKIE_SECURE = env.bool("PROXMOX_COOKIE_SECURE", default=True)

# Realm appended when a student types a bare username ("student1" -> "student1@pve").
PROXMOX_DEFAULT_REALM = env.str("PROXMOX_DEFAULT_REALM", default="pve")

# True: verify Proxmox's HTTPS certificate (use this with a real certificate).
# False: skip verification, for Proxmox's default self-signed certificate (lab use only).
# Or a path to the Proxmox CA file (/etc/pve/pve-root-ca.pem) copied to this machine.
_verify = env.str("PROXMOX_VERIFY_SSL", default="true")
PROXMOX_VERIFY_SSL = {"true": True, "1": True, "false": False, "0": False}.get(_verify.lower(), _verify)
